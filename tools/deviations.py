"""The deviations register: every amendment to every preregistration, in one table (docs/DEVIATIONS.md).

A preregistration is the rule written before a test runs. Every later change to it is an amendment, kept in the
preregistration itself with its reason. This register lists them all, newest first, with the date and the timing the
amendment states for itself: written before any run it governs, after runs began, or not stated. It reads only the
preregistration files, so the same files give the same register on any machine.

  python3 tools/deviations.py           write docs/DEVIATIONS.md
  python3 tools/deviations.py --check   exit 1 if docs/DEVIATIONS.md is not what the preregistrations give now
"""
from __future__ import annotations

import argparse, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.legal import stamp  # noqa: E402

PAGE = ROOT / "docs" / "DEVIATIONS.md"
HEAD = re.compile(r"^#{2,3} (Amendment\b.*)$")
ISO = re.compile(r"(20\d\d)-(\d\d)-(\d\d)")
DAY = re.compile(r"\b(\d{1,2}) (September|October|November)\b(?: (20\d\d))?")
MONTH = {"September": 9, "October": 10, "November": 11}


def date_of(text: str) -> str:
    m = ISO.search(text)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
    m = DAY.search(text)
    if m:
        return f"{m.group(3) or '2026'}-{MONTH[m.group(2)]:02d}-{int(m.group(1)):02d}"
    return "undated"


def timing_of(text: str) -> str:
    t = text.lower()
    if re.search(r"\bbefore (any|the|its|run|counted|a |hardware|every|it)", t) or "written before" in t:
        return "before the runs it governs"
    if re.search(r"\bafter\b", t) or "reruns" in t:
        return "after runs began"
    return "not stated in its heading"


def amendments(root: Path = ROOT):
    out = []
    for f in sorted((root / "docs").glob("*PREREGISTRATION*.md")):
        for line in f.read_text(encoding="utf-8").splitlines():
            m = HEAD.match(line.strip())
            if m:
                h = m.group(1).strip()
                out.append({"date": date_of(h), "file": f.name, "amendment": h, "timing": timing_of(h)})
    out.sort(key=lambda a: (a["date"], a["file"], a["amendment"]), reverse=True)
    return out


def page(rows) -> str:
    by = {}
    for r in rows:
        by[r["timing"]] = by.get(r["timing"], 0) + 1
    files = sorted({r["file"] for r in rows})
    L = ["# The deviations register: every amendment to every preregistration", "",
         "Generated by `python3 tools/deviations.py` from the preregistrations in `docs/`; `tools/deviations.py --check`, run "
         "by `verify.py`, fails a push where this register is not what they give. Each amendment's reason, and what it "
         "changed, is written in the preregistration it amends; this register is the index to all of them, newest first. "
         "The timing is the amendment's own statement in its heading. Earlier windows, runs and tables keep the rule they "
         "ran under, and a three-run table never pools runs from either side of an amendment that changes what it reads.", "",
         f"{len(rows)} amendments in {len(files)} preregistrations: "
         + "; ".join(f"{n} {k}" for k, n in sorted(by.items(), key=lambda kv: -kv[1])) + ".", "",
         "| Date | Preregistration | Amendment | Timing |", "|---|---|---|---|"]
    for r in rows:
        a = r["amendment"].replace("|", "/")
        L.append(f"| {r['date']} | `docs/{r['file']}` | {a} | {r['timing']} |")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = "\n".join(stamp(page(amendments()).split("\n"))) + "\n"
    if args.check:
        ok = PAGE.exists() and PAGE.read_text(encoding="utf-8") == text
        print("deviations register: current" if ok else "deviations register: out of date (python3 tools/deviations.py)")
        return 0 if ok else 1
    PAGE.write_text(text, encoding="utf-8")
    print(f"deviations: {len(amendments())} amendments -> {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
